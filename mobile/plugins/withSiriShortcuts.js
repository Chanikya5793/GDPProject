const ROUTE = `// Generated by plugins/withSiriShortcuts.js — edits here are discarded by prebuild.
import Foundation
import UIKit

/// Hands a dictated phrase to the app through its own URL scheme.
///
/// Going back out through the scheme, rather than reaching into storage from
/// Swift, is what keeps a Siri-created task identical to a typed one: the same
/// screen, the same validation, the same encrypted write, the same audit entry.
@available(iOS 16.0, *)
enum PlannerShortcutRoute {
  struct Draft {
    var title: String?
    var due: Date?
    var priority: PlannerPriority?
    var category: PlannerCategory?
    var notes: String?
  }

  /// Dates cross as yyyy-MM-dd and HH:mm in the device's own timezone, which is
  /// the shape the planner already stores. An ISO instant would be read back as
  /// UTC and land on the previous evening for anyone west of Greenwich.
  private static func dayFormatter() -> DateFormatter {
    let formatter = DateFormatter()
    formatter.locale = Locale(identifier: "en_US_POSIX")
    formatter.calendar = Calendar.current
    formatter.timeZone = TimeZone.current
    formatter.dateFormat = "yyyy-MM-dd"
    return formatter
  }

  private static func timeFormatter() -> DateFormatter {
    let formatter = dayFormatter()
    formatter.dateFormat = "HH:mm"
    return formatter
  }

  static func open(_ screen: String, draft: Draft?) {
    // Built through URLComponents so a dictated phrase containing "&" or "?" is
    // escaped rather than silently truncating everything after it.
    guard var components = URLComponents(string: "nwplanner://" + screen) else { return }

    var items: [URLQueryItem] = []
    if let draft = draft {
      let trimmed = (draft.title ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
      // Present but empty still means "open the form", ready to type into.
      items.append(URLQueryItem(name: "new", value: trimmed))

      if let due = draft.due {
        items.append(URLQueryItem(name: "due", value: dayFormatter().string(from: due)))
        // Siri gives midnight when only a day was said, and a task due "at
        // 00:00" would then alert at midnight, which nobody meant.
        let parts = Calendar.current.dateComponents([.hour, .minute], from: due)
        if (parts.hour ?? 0) != 0 || (parts.minute ?? 0) != 0 {
          items.append(URLQueryItem(name: "at", value: timeFormatter().string(from: due)))
        }
      }
      if let priority = draft.priority {
        items.append(URLQueryItem(name: "priority", value: priority.rawValue))
      }
      if let category = draft.category {
        items.append(URLQueryItem(name: "category", value: category.storedName))
      }
      if let notes = draft.notes, !notes.isEmpty {
        items.append(URLQueryItem(name: "notes", value: notes))
      }
    }
    if !items.isEmpty { components.queryItems = items }

    guard let url = components.url else { return }
    UIApplication.shared.open(url)
  }
}
`;

