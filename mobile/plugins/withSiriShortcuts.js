// Siri and the Shortcuts app, via App Intents.
//
// There is no Expo package for App Intents, so this is Swift the project owns.
// It is injected rather than committed under ios/, because ios/ is generated
// and gitignored — the same reason plugins/withUISceneLifecycle.js exists.
//
// Two shapes of intent live here, and the split is the whole design:
//
//   Writing intents open the app. They carry the dictated values through the
//   app's own URL scheme and let the existing JavaScript do the work, so a task
//   added by voice travels exactly the path a typed one does — encrypted at
//   rest, written through the audit log, queued in the outbox when offline.
//   Creating records natively would mean a second implementation of all of
//   that, in a language with no tests in this repo.
//
//   The reading intent does not open the app. It answers from the App Group
//   container the home screen widgets already read, which costs nothing
//   privacy-wise because those exact numbers are already on the Lock Screen —
//   and it speaks counts and times only, never a record's title, because Siri
//   may be answering on a HomePod or in CarPlay.
//
// What is deliberately absent: AppEntity and EntityQuery, which would let a
// student say "mark Essay draft as done". The system resolves entity
// parameters before perform() runs, with the app possibly not launched and the
// device possibly locked — so answering would mean either reimplementing
// XChaCha20-Poly1305 and the AsyncStorage layout in Swift, or publishing every
// task title into the App Group in plaintext. Both are worse than not having
// the feature.
//
// Credential note: every file here compiles into the existing app target. No
// extension, no new bundle id, no entitlement — App Intents need none, and the
// App Group is already there for the widgets. Nothing in this plugin triggers
// a provisioning change.
//
// Filenames stay flat. withBuildSourceFile derives the Xcode group from the
// file's dirname, and a nested path asserts on a group prebuild never created.

const SHARED_STORE = `// Generated by plugins/withSiriShortcuts.js — edits here are discarded by prebuild.
import Foundation

/// Reads the numbers the app already publishes for the home screen widgets.
///
/// This is the only planner data legible outside the encrypted store, and that
/// is deliberate: counts and clock times, nothing else. Nothing here decrypts
/// anything, because it cannot — the key is in the app's Keychain, marked
/// unlocked-this-device-only, and the ciphertext layout lives in JavaScript.
enum PlannerSharedStore {
  static let suiteName = "group.com.nwmissouri.studentplanner"
  private static let timelineKey = "__expo_widgets_DueToday_timeline"

  struct Snapshot {
    let dueToday: Int
    let overdue: Int
    let doneToday: Int
    let totalToday: Int
    let nextAt: Date?
    let empty: Bool
  }

  static func snapshot(at now: Date = Date()) -> Snapshot? {
    guard let defaults = UserDefaults(suiteName: suiteName),
          let raw = defaults.array(forKey: timelineKey) else { return nil }

    let entries: [(date: Date, props: [String: Any])] = raw.compactMap { element in
      guard let entry = element as? [String: Any],
            let timestamp = entry["timestamp"] as? NSNumber,
            let props = entry["props"] as? [String: Any] else { return nil }
      return (Date(timeIntervalSince1970: timestamp.doubleValue / 1000), props)
    }
    guard !entries.isEmpty else { return nil }

    // The entry in force right now, chosen the same way WidgetKit would: the
    // latest one that has already started, or the earliest if none has.
    let current = entries.filter { $0.date <= now }.max { $0.date < $1.date }
      ?? entries.min { $0.date < $1.date }
    guard let props = current?.props else { return nil }

    let nextAtMs = (props["nextAt"] as? NSNumber)?.doubleValue ?? 0

    return Snapshot(
      dueToday: (props["dueToday"] as? NSNumber)?.intValue ?? 0,
      overdue: (props["overdue"] as? NSNumber)?.intValue ?? 0,
      doneToday: (props["doneToday"] as? NSNumber)?.intValue ?? 0,
      totalToday: (props["totalToday"] as? NSNumber)?.intValue ?? 0,
      nextAt: nextAtMs > 0 ? Date(timeIntervalSince1970: nextAtMs / 1000) : nil,
      empty: (props["empty"] as? NSNumber)?.boolValue ?? true
    )
  }
}
`;

